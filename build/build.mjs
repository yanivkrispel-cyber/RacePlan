// build/build.mjs — assemble the Apps Script web app from the React sources.
//
// No bundler: each src/*.jsx is transpiled with @babel/preset-react (the only
// thing the browser ever needed Babel for — every other syntax used is native
// in the Chrome iframe Apps Script runs in) and wrapped in its own IIFE (the
// files were separate <script> tags; their top-level consts collide if merged).
// image-slot.js and a downscaled data-URI of logo.png are prepended.
//
// The combined script is NOT inlined into the HTML: Apps Script's HtmlService
// sanitizes served pages and silently strips tag-like substrings ("<style>",
// "<img>", …) out of inline <script> string literals, which corrupts
// image-slot.js. Instead we emit it as a string constant in AppJs.gs and serve
// it verbatim through ContentService (which does not sanitize); index.html
// loads it with <script src=".../exec?js=1">.
//
// Outputs (regenerated by `npm run build`, committed for clasp):
//   apps-script/index.html   — small HTML shell (template scriptlets intact)
//   apps-script/AppJs.gs      — var RP_APP_JS = "<the whole app>";

import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import * as babel from '@babel/core';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const r = (...p) => join(ROOT, ...p);

// Script load order — mirrors RacePlan.html exactly.
const JSX_FILES = [
  'src/engine.jsx',
  'src/chart.jsx',
  'src/shared.jsx',
  'src/core.jsx',
  'src/gpx.jsx',
  'src/elevation.jsx',
  'src/map.jsx',
  'src/athletes.jsx',
  'src/planner-b.jsx',
];

// The tiny bootstrap RacePlan.html runs last (data-presets="env,react").
const BOOTSTRAP = `ReactDOM.createRoot(document.getElementById('root')).render(<window.PlannerB />);`;

function transpile(code, filename) {
  return babel.transformSync(code, {
    filename,
    presets: [['@babel/preset-react', { runtime: 'classic' }]],
    compact: false,
    comments: false,
    babelrc: false,
    configFile: false,
  }).code;
}

// logo.png (1180×896, 1.9 MB) → 256 px PNG data URI (~115 KB). Header shows it
// at 72×72, so 256 px is retina-sharp.
function logoDataUri() {
  const py = [
    'import base64, io, sys',
    'from PIL import Image',
    "im = Image.open(r'" + r('logo.png') + "').convert('RGBA')",
    'im.thumbnail((256, 256), Image.LANCZOS)',
    'buf = io.BytesIO()',
    "im.save(buf, format='PNG', optimize=True)",
    "sys.stdout.write('data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode())",
  ].join('\n');
  const bin = process.platform === 'win32' ? 'python' : 'python3';
  return execFileSync(bin, ['-c', py], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
}

// ── assemble the app script ──────────────────────────────────────────────
const imageSlot = readFileSync(r('image-slot.js'), 'utf8');

const transpiled = JSX_FILES.map((f) => {
  const src = readFileSync(r(f), 'utf8');
  return `/* ===== ${f} ===== */\n(function () {\n${transpile(src, f)}\n})();`;
}).join('\n\n');

const logo = logoDataUri();

const appScript = [
  '// <image-slot> web component',
  imageSlot,
  '',
  '// RacePlan logo (downscaled, inlined by build/build.mjs)',
  `window.__RACEPLAN_LOGO__ = ${JSON.stringify(logo)};`,
  '',
  '// ===== transpiled React sources =====',
  transpiled,
  '',
  '// ===== bootstrap =====',
  transpile(BOOTSTRAP, 'bootstrap.jsx'),
  '',
].join('\n');

// ── write AppJs.gs ──────────────────────────────────────────────────────
const gs = [
  '// GENERATED by build/build.mjs — do not edit.',
  '// The full RacePlan client script, served verbatim by doGet(?js=1) through',
  '// ContentService so HtmlService sanitization never touches it.',
  '',
  'var RP_APP_JS = ' + JSON.stringify(appScript) + ';',
  '',
].join('\n');
writeFileSync(r('apps-script/AppJs.gs'), gs);

// ── write index.html (shell only) ───────────────────────────────────────
const html = readFileSync(r('build/index.template.html'), 'utf8');
writeFileSync(r('apps-script/index.html'), html);

const kb = (n) => (n / 1024).toFixed(1) + ' KB';
console.log('built apps-script/{index.html, AppJs.gs}');
console.log('  logo data URI : ' + kb(logo.length));
console.log('  app script    : ' + kb(appScript.length));
console.log('  AppJs.gs      : ' + kb(gs.length));
console.log('  index.html    : ' + kb(html.length));
