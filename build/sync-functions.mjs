// build/sync-functions.mjs — copy the shared pure modules into functions/ (Cloud Functions deploy only
// that folder). test/watch.test.mjs fails if the copy is stale. Run by `npm run build` and as the
// functions predeploy hook in firebase.json.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const PAIRS = [['src/watch.jsx', 'functions/watchplan.js']];

const HEADER = '// GENERATED by build/sync-functions.mjs from src/watch.jsx -- do not edit here.\n';
export const expected = (src) => HEADER + readFileSync(join(ROOT, src), 'utf8');

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const [src, dst] of PAIRS) {
    writeFileSync(join(ROOT, dst), expected(src));
    console.log(`synced ${src} -> ${dst}`);
  }
}
